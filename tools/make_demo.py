from PIL import Image, ImageDraw, ImageFont

OUT = Path(__file__).resolve().parent.parent / "demo"
OUT.mkdir(exist_ok=True)
FONT_DIR = "/usr/share/fonts/truetype/dejavu/"
pdfmetrics.registerFont(TTFont("DV", FONT_DIR + "DejaVuSans.ttf"))
pdfmetrics.registerFont(TTFont("DVB", FONT_DIR + "DejaVuSans-Bold.ttf"))

H1 = ParagraphStyle("h1", fontName="DVB", fontSize=15, leading=19, spaceAfter=8)
H2 = ParagraphStyle("h2", fontName="DVB", fontSize=11.5, leading=15, spaceBefore=10, spaceAfter=5)
P = ParagraphStyle("p", fontName="DV", fontSize=10, leading=14, spaceAfter=5)
SMALL = ParagraphStyle("s", fontName="DV", fontSize=8.5, leading=11)
NOTE = ParagraphStyle("n", fontName="DV", fontSize=8.5, leading=11, textColor=colors.grey)


def docx(name, title, blocks):
    d = Document()
    d.add_heading(title, level=0)
    for kind, val in blocks:
        if kind == "h":
            d.add_heading(val, level=1)
        elif kind == "p":
            d.add_paragraph(val)
        elif kind == "table":
            t = d.add_table(rows=0, cols=len(val[0]))
            t.style = "Table Grid"
            for row in val:
                cells = t.add_row().cells
                for c, v in zip(cells, row):
                    c.text = v
    d.save(OUT / name)


def pdf(name, title, story_blocks):
    story = [Paragraph(title, H1)]
    for kind, val in story_blocks:
        if kind == "h":
            story.append(Paragraph(val, H2))
        elif kind == "p":
            story.append(Paragraph(val, P))
        elif kind == "note":
            story.append(Paragraph(val, NOTE))
        elif kind == "break":
            story.append(PageBreak())
        elif kind == "table":
            data = [[Paragraph(c, SMALL) for c in row] for row in val["rows"]]
            t = Table(data, colWidths=[w * mm for w in val["widths"]])
            t.setStyle(TableStyle([
                ("GRID", (0, 0), (-1, -1), 0.4, colors.grey),
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#EEF1F5")),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ]))
            story.append(t)
            story.append(Spacer(1, 6))

    def footer(c, d):
        c.setFont("DV", 8)
        c.setFillColor(colors.grey)
        c.drawString(20 * mm, 10 * mm, "Демонстрационный документ. Организации и лица вымышлены.")
        c.drawRightString(190 * mm, 10 * mm, f"Стр. {d.page}")

    SimpleDocTemplate(str(OUT / name), pagesize=A4, leftMargin=20 * mm, rightMargin=20 * mm,
                      topMargin=18 * mm, bottomMargin=18 * mm, title=title,
                      author="Демо").build(story, onFirstPage=footer, onLaterPages=footer)


